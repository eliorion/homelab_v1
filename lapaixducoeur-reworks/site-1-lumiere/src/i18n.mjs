// French typography: narrow no-break spaces before high punctuation and inside guillemets.
export const typo = (s, lang) => {
  if (lang !== 'fr' || typeof s !== 'string') return s;
  return s
    .replace(/ ([:;!?»])/g, ' $1')
    .replace(/« /g, '« ')
    .replace(/(\d) \$/g, '$1 $');
};
